#!/usr/bin/env python3
"""Reconcile DECLARED control-plane values against MEASURED current evidence (fail-closed).

WHY THIS EXISTS
---------------
Two whole trading days were lost in one week to the same defect class, wearing different clothes:

  * 2026-08-03 — manifest drift. CRITICAL-covered files were modified across a scheduled-run
    boundary without a re-sign. The gate DID detect it, but only at 05:38, when the window had
    already closed.
  * 2026-08-04 — namespace drift. `broker_namespace_policy` DECLARED a Robinhood namespace that
    no longer existed. Nothing compared it against the live registry, so the read path was dead
    for ten trading sessions while `validate_broker_permissions.py` reported PASS.

Both are the same shape: the control plane holds a **declared** value that is only true while a
human keeps it hand-synced to a **measured** fact, with no reconciliation and no consequence that
forces resolution before the next scheduled run. Every previous remediation replaced one
hand-synced declaration with a different hand-synced declaration, which is why each closed a hole
and none closed the class.

This tool closes the class by asserting a small, closed list of declared-vs-measured invariants
and reporting them at a moment when acting is still possible — a session-start / end-of-day check
and the evening pre-session job — rather than at 05:38 the next morning.

INVARIANTS
----------
  1. broker_live_namespace   declared ROBINHOOD_LIVE_NAMESPACE == a mounted+connected server in a
                             FRESH measured attestation (freshness is a property of the
                             measurement, never of the reviewed audit)
  2. broker_namespace_snapshot  data/broker_tool_namespace.json recognizes the declared live
                             namespace AND every retired one, so retired-namespace denies still
                             bind to a known name
  3. broker_read_allowlist   every declared live collector read is in READ_ALLOWLIST
  4. collector_tool_contract config/robinhood_verifier.yaml lists EXACTLY the declared live set
  5. research_ledger_references  every append-only ledger `report_path` resolves on disk
                             (detection only — the ledger is never rewritten)
  6. integrity_manifest      the signed manifest still matches the working tree (build_manifest
                             --check, which is read-only: reconciliation never re-signs, because
                             that would turn "you have drifted" into "the drift is now accepted")

SAFETY
------
Read-only. No broker tool, no model, no order, no money movement, no repo mutation. Writes at most
one artifact under data/runtime/health/. Grants no authority; every verdict is advisory-to-the-
operator and fail-closed for automation.

Exit 0 = all invariants hold. Exit 5 = at least one divergence. Exit 2 = could not evaluate.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "scripts" / "lib"))

import broker_namespace_policy as namespace_policy  # noqa: E402
import mcp_registry_probe  # noqa: E402
import validate_broker_permissions as broker_permissions  # noqa: E402

SCHEMA = "control_plane_reconciliation/1.0"
# A measured attestation older than this means nobody has looked recently.
DEFAULT_ATTESTATION_MAX_AGE_MINUTES = 720
VERIFIER_CONFIG = ROOT / "config" / "robinhood_verifier.yaml"


def _finding(check: str, ok: bool, detail: str, measured=None, declared=None) -> dict:
    return {
        "check": check,
        "ok": bool(ok),
        "detail": detail,
        "declared": declared,
        "measured": measured,
    }


def _check_live_namespace(registry_path: Path, max_age_minutes: int) -> dict:
    """Freshness belongs to the MEASUREMENT, not to the reviewed audit.

    The attestation is a runtime artifact regenerated by every collector run and by the evening
    preflight, so a stale one means nobody has measured recently — which is indistinguishable, for
    this purpose, from not knowing.
    """
    declared = namespace_policy.ROBINHOOD_LIVE_NAMESPACE
    document = None
    if registry_path.is_file():
        try:
            document = json.loads(registry_path.read_text(encoding="utf-8"))
        except Exception:
            document = None
    # Sourced from the probe module, never re-literalled: a hardcoded copy here silently rejected
    # every attestation the moment the probe schema moved 1.0 -> 1.1, reporting "no usable
    # attestation" for a perfectly good measurement. Same single-source rule as the namespace.
    if not isinstance(document, dict) or document.get("schema") != mcp_registry_probe.SCHEMA:
        return _finding("broker_live_namespace", False,
                        "no usable measured registry attestation "
                        "(run scripts/mcp_registry_probe.py)",
                        measured=None, declared=declared)
    robinhood = document.get("robinhood") or {}
    classification = robinhood.get("classification")
    problems = []
    if classification != namespace_policy.LIVE_PRESENCE_OK:
        problems.append(f"declared live namespace unusable: {classification}")
    if robinhood.get("declared_live_namespace") != declared:
        problems.append(
            f"attestation was taken for {robinhood.get('declared_live_namespace')!r}, "
            f"policy declares {declared!r}")
    age_minutes = None
    try:
        stamped = datetime.fromisoformat(str(document.get("generated_utc")))
        if stamped.tzinfo is None:
            stamped = stamped.replace(tzinfo=timezone.utc)
        age_minutes = round((datetime.now(timezone.utc) - stamped).total_seconds() / 60.0, 1)
    except Exception:
        problems.append("attestation has no usable timestamp")
    if age_minutes is not None and age_minutes > max_age_minutes:
        problems.append(f"attestation is {age_minutes:.0f}m old (budget {max_age_minutes}m)")
    return _finding("broker_live_namespace", not problems,
                    "; ".join(problems) if problems
                    else "declared live namespace is mounted and connected",
                    measured={"classification": classification, "age_minutes": age_minutes},
                    declared=declared)


def _check_namespace_snapshot() -> dict:
    """The snapshot is a REVIEWED audit of tool categories, not a measurement.

    Its `captured_*` date is the date that audit was performed and re-stamping it without a
    re-audit would be a lie, so no staleness budget is applied here. What must hold is the
    identity invariant: the declared live namespace has to be recognized, and every retired
    namespace has to remain recognized so its mutation denies still bind to a known name.
    """
    path = broker_permissions.DEFAULT_SNAPSHOT
    try:
        snapshot = json.loads(Path(path).read_text(encoding="utf-8"))
    except Exception as exc:
        return _finding("broker_namespace_snapshot", False,
                        f"namespace snapshot unreadable: {exc}")
    recognized = set(snapshot.get("recognized_broker_servers") or [])
    declared = namespace_policy.ROBINHOOD_LIVE_NAMESPACE
    problems = []
    if declared not in recognized:
        problems.append(f"declared namespace {declared!r} not in recognized_broker_servers")
    unrecognized_retired = sorted(
        set(namespace_policy.ROBINHOOD_RETIRED_NAMESPACES) - recognized)
    if unrecognized_retired:
        problems.append(
            f"retired namespace(s) no longer recognized (their denies would not bind): "
            f"{unrecognized_retired}")
    return _finding("broker_namespace_snapshot", not problems,
                    "; ".join(problems) if problems
                    else "snapshot recognizes the declared live and retired namespaces",
                    measured={"audited_utc": snapshot.get("captured_utc"),
                              "recognized_count": len(recognized)},
                    declared=declared)


def _check_read_allowlist() -> dict:
    missing = sorted(set(namespace_policy.COLLECTOR_LIVE_TOOLS)
                     - set(broker_permissions.READ_ALLOWLIST))
    return _finding("broker_read_allowlist", not missing,
                    "every declared live read is allowlisted" if not missing
                    else f"{len(missing)} declared live read(s) missing from READ_ALLOWLIST",
                    measured=missing)


def _check_collector_tool_contract() -> dict:
    try:
        import yaml
        config = yaml.safe_load(VERIFIER_CONFIG.read_text(encoding="utf-8")) or {}
    except Exception as exc:
        return _finding("collector_tool_contract", False,
                        f"verifier config unreadable: {exc}")
    configured = ((config.get("collector") or {}).get("allowed_read_tools")) or []
    if not isinstance(configured, list) or any(not isinstance(x, str) for x in configured):
        return _finding("collector_tool_contract", False, "allowed_read_tools malformed")
    expected = set(namespace_policy.COLLECTOR_LIVE_TOOLS)
    got = set(configured)
    extra, missing = sorted(got - expected), sorted(expected - got)
    ok = not extra and not missing
    return _finding("collector_tool_contract", ok,
                    "configured read inventory equals the declared live set" if ok
                    else f"extra={len(extra)} missing={len(missing)}",
                    measured={"extra": extra, "missing": missing})


def _check_research_ledger_references() -> dict:
    """Every ledger `report_path` must resolve to a file that exists on disk.

    Same declared-vs-measured class: the append-only ledger DECLARES a frozen report; the file
    system is the measurement. Two entries (2026-07-13 preliminary, 2026-07-29 preliminary)
    reference artifacts that exist in neither the working tree, git history, nor
    data/MANIFEST.json, and nothing noticed for weeks.

    Detection only. The ledger is append-only and its own header forbids rewriting or relabeling
    entries, so this NEVER edits, backfills or fabricates a report; a correction is an operator
    governance act that appends its own timestamped entry.
    """
    path = ROOT / "data" / "research_ledger.json"
    try:
        document = json.loads(path.read_text(encoding="utf-8"))
    except Exception as exc:
        return _finding("research_ledger_references", False, f"ledger unreadable: {exc}")
    entries = document.get("entries") if isinstance(document, dict) else None
    if not isinstance(entries, list):
        return _finding("research_ledger_references", False, "ledger entries malformed")
    try:
        import research_metrics
        status = research_metrics.dangling_report_references(ROOT)
    except Exception as exc:
        return _finding("research_ledger_references", False,
                        f"dangling-reference reconciliation failed: {exc}")
    unresolved = status["unresolved"]
    acknowledged = status["acknowledged"]
    detail = ("every ledger report_path resolves on disk"
              if not unresolved and not acknowledged else
              f"{len(unresolved)} unresolved dangling reference(s); "
              f"{len(acknowledged)} acknowledged by an append-only correction record")
    if unresolved:
        detail = (f"{len(unresolved)} UNRESOLVED dangling reference(s) — append a "
                  f"research_ledger_correction/1.0 record (never edit the entry, never "
                  f"reconstruct the report)")
    return _finding("research_ledger_references", not unresolved, detail,
                    measured={"entry_count": len(entries),
                              "unresolved": unresolved,
                              "acknowledged": acknowledged})


def _check_integrity_manifest() -> dict:
    script = ROOT / "scripts" / "build_manifest.py"
    if not script.is_file():
        return _finding("integrity_manifest", False, "no manifest verifier found")
    # --check is READ-ONLY by contract: it compares current CRITICAL hashes to the stored
    # manifest and never writes. Reconciliation must never re-sign as a side effect — that would
    # turn "you have drifted" into "you have silently accepted the drift".
    args = [sys.executable, str(script), "--check"]
    try:
        completed = subprocess.run(args, capture_output=True, text=True, timeout=180,
                                   cwd=str(ROOT), check=False, stdin=subprocess.DEVNULL)
    except Exception as exc:
        return _finding("integrity_manifest", False, f"manifest verification failed to run: {exc}")
    ok = completed.returncode == 0
    tail = (completed.stdout or completed.stderr or "").strip().splitlines()
    return _finding("integrity_manifest", ok,
                    "signed manifest matches the working tree" if ok
                    else f"manifest verification exit {completed.returncode}: "
                         f"{tail[-1][:200] if tail else 'no output'}",
                    measured={"exit_code": completed.returncode})


def reconcile(target: str, *, registry_path: Path,
              attestation_max_age_minutes: int = DEFAULT_ATTESTATION_MAX_AGE_MINUTES,
              skip_manifest: bool = False) -> dict:
    findings = [
        _check_live_namespace(registry_path, attestation_max_age_minutes),
        _check_namespace_snapshot(),
        _check_read_allowlist(),
        _check_collector_tool_contract(),
        _check_research_ledger_references(),
    ]
    if not skip_manifest:
        findings.append(_check_integrity_manifest())
    diverged = [row["check"] for row in findings if not row["ok"]]
    return {
        "schema": SCHEMA,
        "target_session_date": target,
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "ok": not diverged,
        "status": "reconciled" if not diverged else "diverged",
        "diverged_checks": diverged,
        "findings": findings,
        "safety": {
            "read_only": True,
            "broker_invoked": False,
            "model_invoked": False,
            "execution_enabled": False,
            "activation_authority": False,
            "grants_no_authority": True,
        },
    }


def default_target() -> str:
    from zoneinfo import ZoneInfo
    return datetime.now(ZoneInfo("America/Los_Angeles")).strftime("%Y-%m-%d")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--target", default=None)
    parser.add_argument("--registry", default=None,
                        help="mcp_registry_probe attestation "
                             "(default data/runtime/health/<target>_mcp_registry.json)")
    parser.add_argument("--out", default=None, help="artifact path; omit to skip writing")
    parser.add_argument("--attestation-max-age-minutes", type=int,
                        default=DEFAULT_ATTESTATION_MAX_AGE_MINUTES)
    parser.add_argument("--skip-manifest", action="store_true",
                        help="skip the manifest invariant (it is the slowest check)")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()

    target = args.target or default_target()
    registry = Path(args.registry) if args.registry else (
        ROOT / "data" / "runtime" / "health" / f"{target}_mcp_registry.json")
    try:
        result = reconcile(target, registry_path=registry,
                           attestation_max_age_minutes=args.attestation_max_age_minutes,
                           skip_manifest=args.skip_manifest)
    except Exception as exc:
        print(json.dumps({"ok": False, "status": "error", "error": str(exc)}))
        return 2

    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        tmp = out.with_suffix(out.suffix + ".tmp")
        tmp.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        os.chmod(tmp, 0o600)
        tmp.replace(out)

    if args.json:
        print(json.dumps(result, indent=2, sort_keys=True))
    elif not args.quiet:
        print(f"CONTROL-PLANE RECONCILIATION: {result['status'].upper()}")
        for row in result["findings"]:
            print(f"  [{'ok  ' if row['ok'] else 'DIFF'}] {row['check']}: {row['detail']}")
    return 0 if result["ok"] else 5


if __name__ == "__main__":
    raise SystemExit(main())
